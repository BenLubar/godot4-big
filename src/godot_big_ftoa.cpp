// Text converts the floating-point number x to a string according
// to the given format and precision prec. The format is one of:
//
//	'e'	-d.dddde±dd, decimal exponent, at least two (possibly 0) exponent digits
//	'E'	-d.ddddE±dd, decimal exponent, at least two (possibly 0) exponent digits
//	'f'	-ddddd.dddd, no exponent
//	'g'	like 'e' for large exponents, like 'f' otherwise
//	'G'	like 'E' for large exponents, like 'f' otherwise
//	'x'	-0xd.dddddp±dd, hexadecimal mantissa, decimal power of two exponent
//	'p'	-0x.dddp±dd, hexadecimal mantissa, decimal power of two exponent (non-standard)
//	'b'	-ddddddp±dd, decimal mantissa, decimal power of two exponent (non-standard)
//
// For the power-of-two exponent formats, the mantissa is printed in normalized form:
//
//	'x'	hexadecimal mantissa in [1, 2), or 0
//	'p'	hexadecimal mantissa in [½, 1), or 0
//	'b'	decimal integer mantissa using x.Prec() bits, or 0
//
// Note that the 'x' form is the one used by most other languages and libraries.
//
// If format is a different character, Text returns a "%" followed by the
// unrecognized format character.
//
// The precision prec controls the number of digits (excluding the exponent)
// printed by the 'e', 'E', 'f', 'g', 'G', and 'x' formats.
// For 'e', 'E', 'f', and 'x', it is the number of digits after the decimal point.
// For 'g' and 'G' it is the total number of digits. A negative precision selects
// the smallest number of decimal digits necessary to identify the value x uniquely
// using x.Prec() mantissa bits.
// The prec value is ignored for the 'b' and 'p' formats.
//
// Note that Text may return a different result than strconv.FormatFloat for
// corresponding arguments if the matching float32 or float64 number provided
// to strconv.FormatFloat is a denormalized number.

// String formats x like x.Text('g', 10).
// (String must be called explicitly, [Float.Format] does not support %s verb.)

// Append appends to buf the string form of the floating-point number x,
// as generated by x.Text, and returns the extended buffer.
String BigFloat::String(Format p_format, int64_t p_prec) const {
	PackedByteArray buf;

	// sign
	if (_neg) {
		buf.append('-');
	}

	// Inf
	if (_form == FORM_INF) {
		if (!_neg) {
			buf.append('+');
		}
		return buf.get_string_from_ascii() + "Inf";
	}

	// pick off easy formats
	if (p_format == FORMAT_DECIMAL) {
		return _fmtB(buf);
	}
	if (p_format == FORMAT_HEX_NORMAL) {
		return _fmtP(buf);
	}
	if (p_format == FORMAT_HEX) {
		return _fmtX(buf, p_prec);
	}

	// Algorithm:
	//   1) convert Float to multiprecision decimal
	//   2) round to desired precision
	//   3) read digits out and format

	// 1) convert Float to multiprecision decimal
	BigDecimal d; // == 0.0
	if (_form == FORM_FINITE) {
		// x != 0
		d.init(_mant, static_cast<int64_t>(_exp) - _mant.bitLen());
	}

	// 2) round to desired precision
	bool shortest = false;
	if (p_prec < 0) {
		shortest = true;
		d.roundShortest(this);

		// Precision for shortest representation mode.
		if (p_format == FORMAT_SCIENTIFIC || p_format == FORMAT_SCIENTIFIC_UPPER) {
			p_prec = d.mant.size() - 1;
		} else if (p_format == FORMAT_PLAIN) {
			p_prec = Math::max(d.mant.size() - d.exp, INT64_C(0));
		} else if (p_format == FORMAT_AUTO || p_format == FORMAT_AUTO_UPPER) {
			p_prec = d.mant.size();
		}
	} else {
		// round appropriately
		if (p_format == FORMAT_SCIENTIFIC || p_format == FORMAT_SCIENTIFIC_UPPER) {
			// one digit before and number of digits after decimal point
			d.round(1 + p_prec);
		} else if (p_format == FORMAT_PLAIN) {
			// number of digits before and after decimal point
			d.round(d.exp + p_prec);
		} else if (p_format == FORMAT_AUTO || p_format == FORMAT_AUTO_UPPER) {
			if (p_prec == 0) {
				p_prec = 1;
			}
			d.round(p_prec);
		}
	}

	// 3) read digits out and format
	if (p_format == FORMAT_SCIENTIFIC || p_format == FORMAT_SCIENTIFIC_UPPER) {
		return _fmtE(buf, p_format, p_prec, d);
	}
	if (p_format == FORMAT_PLAIN) {
		return _fmtF(buf, p_prec, d);
	}
	if (p_format == FORMAT_AUTO || p_format == FORMAT_AUTO_UPPER) {
		// trim trailing fractional zeros in %e format
		int64_t eprec = p_prec;
		if (eprec > d.mant.size() && d.mant.size() >= d.exp) {
			eprec = d.mant.size();
		}
		// %e is used if the exponent from the conversion
		// is less than -4 or greater than or equal to the precision.
		// If precision was the shortest possible, use eprec = 6 for
		// this decision.
		if (shortest) {
			eprec = 6;
		}
		int64_t exp = d.exp - 1;
		if (exp < -4 || exp >= eprec) {
			return _fmtE(buf, static_cast<Format>(p_format + 'e' - 'g'), Math::min(p_prec, d.mant.size()) - 1, d);
		}
		if (p_prec > d.exp) {
			p_prec = d.mant.size();
		}
		return _fmtF(buf, Math::max(p_prec - d.exp, INT64_C(0)), d);
	}

	// unknown format
	return vformat("%%%c", p_format);
}

void BigDecimal::roundShortest(const BigFloat *p_x) {
	// if the mantissa is zero, the number is zero - stop now
	if (mant.is_empty()) {
		return;
	}

	// Approach: All numbers in the interval [x - 1/2ulp, x + 1/2ulp]
	// (possibly exclusive) round to x for the given precision of x.
	// Compute the lower and upper bound in decimal form and find the
	// shortest decimal number d such that lower <= d <= upper.

	// 1) Compute normalized mantissa mant and exponent exp for x such
	// that the lsb of mant corresponds to 1/2 ulp for the precision of
	// x (i.e., for mant we want x.prec + 1 bits).
	BigNat xmant{ p_x->_mant };
	int64_t xexp = static_cast<int64_t>(p_x->_exp) - xmant.bitLen();
	int64_t s = xmant.bitLen() - static_cast<int64_t>(p_x->_prec) - 1;
	if (s < 0) {
		xmant.lsh(xmant, static_cast<uint64_t>(-s));
	} else if (s > 0) {
		xmant.rsh(xmant, static_cast<uint64_t>(+s));
	}
	xexp += s;
	// x = mant * 2**exp with lsb(mant) == 1/2 ulp of x.prec

	// 2) Compute lower bound by subtracting 1/2 ulp.
	BigDecimal lower;
	BigNat tmp;
	tmp.sub1(xmant);
	lower.init(tmp, xexp);

	// 3) Compute upper bound by adding 1/2 ulp.
	BigDecimal upper;
	tmp.add1(xmant);
	upper.init(tmp, xexp);

	// The upper and lower bounds are possible outputs only if
	// the original mantissa is even, so that ToNearestEven rounding
	// would round to the original mantissa and not the neighbors.
	const bool inclusive = (xmant[0] & 2) == 0; // test bit 1 since original mantissa was shifted by 1

	// Now we can figure out the minimum number of digits required.
	// Walk along until d has distinguished itself from upper and lower.
	const char *dmant = reinterpret_cast<const char *>(mant.ptr());
	for (int64_t i = 0; i < mant.size(); i++) {
		const char m = dmant[i];
		const char l = lower.at(i);
		const char u = upper.at(i);

		// Okay to round down (truncate) if lower has a different digit
		// or if lower is inclusive and is exactly the result of rounding
		// down (i.e., and we have reached the final digit of lower).
		const bool okdown = l != m || (inclusive && i + 1 == lower.mant.size());

		// Okay to round up if upper has a different digit and either upper
		// is inclusive or upper is bigger than the result of rounding up.
		// The last clause handles digits past upper's trimmed mantissa:
		// upper.at(i) returns '0' there, but the true upper bound was
		// determined by earlier digits, so rounding up is valid unless
		// m == '9' (which would carry onto the exclusive upper bound).
		// See also go.dev/issue/80206.
		const bool okup = m != u && (inclusive || m + 1 < u || i + 1 < upper.mant.size() || (i >= upper.mant.size() && m < '9'));

		// If it's okay to do either, then round to the nearest one.
		// If it's okay to do only one, do it.
		if (okdown && okup) {
			round(i + 1);
			return;
		}
		if (okdown) {
			roundDown(i + 1);
			return;
		}
		if (okup) {
			roundUp(i + 1);
			return;
		}
	}
}

// %e: d.ddddde±dd
String BigFloat::_fmtE(PackedByteArray &buf, Format fmt, int64_t prec, BigDecimal &d) {
	// first digit
	char ch = '0';
	if (!d.mant.is_empty()) {
		ch = d.mant[0];
	}
	buf.append(ch);

	// .moredigits
	if (prec > 0) {
		buf.append('.');
		int64_t i = 1;
		const int64_t m = Math::min(d.mant.size(), prec + 1);
		if (i < m) {
			buf.append_array(d.mant.slice(i, m));
			i = m;
		}
		for (; i <= prec; i++) {
			buf.append('0');
		}
	}

	// e±
	buf.append(fmt);
	int64_t exp = 0;
	if (!d.mant.is_empty()) {
		exp = d.exp - 1; // -1 because first digit was printed before '.'
	}
	if (exp < 0) {
		ch = '-';
		exp = -exp;
	} else {
		ch = '+';
	}
	buf.append(ch);

	// dd...d
	if (exp < 10) {
		buf.append('0'); // at least 2 exponent digits
	}
	return buf.get_string_from_ascii() + String::num_int64(exp);
}

// %f: ddddddd.ddddd
String BigFloat::_fmtF(PackedByteArray &buf, int64_t prec, BigDecimal &d) {
	// integer, padded with zeros as needed
	if (d.exp > 0) {
		int64_t m = Math::min(d.mant.size(), d.exp);
		buf.append_array(d.mant.slice(0, m));
		for (; m < d.exp; m++) {
			buf.append('0');
		}
	} else {
		buf.append('0');
	}

	// fraction
	if (prec > 0) {
		buf.append('.');
		for (int64_t i = 0; i < prec; i++) {
			buf.append(d.at(d.exp + i));
		}
	}

	return buf.get_string_from_ascii();
}

// fmtB appends the string of x in the format mantissa "p" exponent
// with a decimal mantissa and a binary exponent, or "0" if x is zero,
// and returns the extended buffer.
// The mantissa is normalized such that is uses x.Prec() bits in binary
// representation.
// The sign of x is ignored, and x must not be an Inf.
// (The caller handles Inf before invoking fmtB.)
String BigFloat::_fmtB(PackedByteArray &buf) const {
	if (_form == FORM_ZERO) {
		buf.append('0');
		return buf.get_string_from_ascii();
	}

#ifdef DEBUG_FLOAT_ENABLED
	CRASH_COND_MSG(_form != FORM_FINITE, "non-finite float");
#endif
	// x != 0

	// adjust mantissa to use exactly x.prec bits
	BigNat m{ _mant };
	const uint32_t w = static_cast<uint32_t>(_mant.array.size()) * 64;
	if (w < _prec) {
		m.lsh(m, _prec - w);
	} else if (w > _prec) {
		m.rsh(m, w - _prec);
	}

	buf.append_array(m.utoa(10));
	buf.append('p');
	const int64_t e = static_cast<int64_t>(_exp) - static_cast<int64_t>(_prec);
	if (e >= 0) {
		buf.append('+');
	}
	return buf.get_string_from_ascii() + String::num_int64(e);
}

// fmtX appends the string of x in the format "0x1." mantissa "p" exponent
// with a hexadecimal mantissa and a binary exponent, or "0x0p0" if x is zero,
// and returns the extended buffer.
// A non-zero mantissa is normalized such that 1.0 <= mantissa < 2.0.
// The sign of x is ignored, and x must not be an Inf.
// (The caller handles Inf before invoking fmtX.)
String BigFloat::_fmtX(PackedByteArray &buf, int64_t prec) const {
	if (_form == FORM_ZERO) {
		buf.append_array({ '0', 'x', '0' });
		if (prec > 0) {
			buf.append('.');
			for (int64_t i = 0; i < prec; i++) {
				buf.append('0');
			}
		}
		buf.append_array({ 'p', '+', '0', '0' });
		return buf.get_string_from_ascii();
	}

#ifdef DEBUG_FLOAT_ENABLED
	CRASH_COND_MSG(_form != FORM_FINITE, "non-finite float");
#endif

	// round mantissa to n bits
	uint64_t n;
	if (prec < 0) {
		n = 1 + ((static_cast<uint64_t>(MinPrec()) - 1 + 3) / 4 * 4); // round MinPrec up to 1 mod 4
	} else {
		n = 1 + (4 * static_cast<uint64_t>(prec));
	}
	// n%4 == 1
	Ref<BigFloat> x{ memnew(BigFloat) };
	x->SetPrec(n);
	x->SetMode(_mode);
	x->Set(const_cast<BigFloat *>(this));

	// adjust mantissa to use exactly n bits
	BigNat m = x->_mant;
	const uint64_t w = static_cast<uint64_t>(m.array.size()) * 64;
	if (w < n) {
		m.lsh(m, n - w);
	} else if (w > n) {
		m.rsh(m, w - n);
	}
	int64_t exp64 = static_cast<int64_t>(x->_exp) - 1; // avoid wrap-around

	const PackedByteArray hm = m.utoa(16);
#ifdef DEBUG_FLOAT_ENABLED
	CRASH_COND_MSG(hm[0] != '1', "incorrect mantissa: " + hm.get_string_from_ascii());
#endif
	buf.append_array({ '0', 'x', '1' });
	if (hm.size() > 1) {
		buf.append('.');
		buf.append_array(hm.slice(1));
	}

	buf.append('p');
	if (exp64 >= 0) {
		buf.append('+');
	} else {
		exp64 = -exp64;
		buf.append('-');
	}
	// Force at least two exponent digits, to match fmt.
	if (exp64 < 10) {
		buf.append('0');
	}
	return buf.get_string_from_ascii() + String::num_int64(exp64);
}

// fmtP appends the string of x in the format "0x." mantissa "p" exponent
// with a hexadecimal mantissa and a binary exponent, or "0" if x is zero,
// and returns the extended buffer.
// The mantissa is normalized such that 0.5 <= 0.mantissa < 1.0.
// The sign of x is ignored, and x must not be an Inf.
// (The caller handles Inf before invoking fmtP.)
String BigFloat::_fmtP(PackedByteArray &buf) const {
	if (_form == FORM_ZERO) {
		buf.append('0');
		return buf.get_string_from_ascii();
	}

#ifdef DEBUG_FLOAT_ENABLED
	CRASH_COND_MSG(_form != FORM_FINITE, "non-finite float");
#endif
	// x != 0

	// remove trailing 0 words early
	// (no need to convert to hex 0's and trim later)
	BigNat m{ _mant };
	int64_t i = 0;
	while (i < m.array.size() && m[i] == 0) {
		i++;
	}
	m.array = m.array.slice(i);

	buf.append_array({ '0', 'x', '.' });

	const PackedByteArray mn = m.utoa(16);
	i = mn.size();
	while (i > 0 && mn[i - 1] == '0') {
		i--;
	}
	buf.append_array(mn.slice(0, i));

	buf.append('p');
	if (_exp >= 0) {
		buf.append('+');
	}
	return buf.get_string_from_ascii() + String::num_int64(_exp);
}
